-- Admin second factor (TOTP), backup codes and second-factor sessions. Secrets are AES-GCM encrypted by the
-- application (TOTP_ENCRYPTION_KEY); codes and session tokens are stored only as hashes.
CREATE TABLE IF NOT EXISTS admin_two_factor (
    username VARCHAR(100) PRIMARY KEY,
    secret_ciphertext VARCHAR(200),
    pending_secret_ciphertext VARCHAR(200),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    last_used_step BIGINT NOT NULL DEFAULT 0,
    enrolled_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS admin_backup_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    code_hash VARCHAR(100) NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_admin_backup_codes_user ON admin_backup_codes (username);

CREATE TABLE IF NOT EXISTS admin_sessions (
    token_hash VARCHAR(64) PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    created_ip VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_admin_sessions_expires ON admin_sessions (expires_at);
