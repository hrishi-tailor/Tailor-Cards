-- Business ledger: what the store bought (lots) and what it sold from them (sales).
-- A lot is one purchase at one total cost: a single card, a slab, or a whole sealed case. Sales draw units
-- from a lot, so a case of 10 ETBs can be sold over several sales at different prices (a price of 0 records a
-- giveaway). Cost of goods for a sale is the lot's average unit cost times the units sold.
CREATE TABLE IF NOT EXISTS ledger_lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    card_ref VARCHAR(100),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    total_cost_cad NUMERIC(12, 2) NOT NULL CHECK (total_cost_cad >= 0),
    acquired_on DATE,
    acquired_channel VARCHAR(30),
    listed_on DATE,
    listed_price_cad NUMERIC(12, 2) CHECK (listed_price_cad >= 0),
    notes VARCHAR(500),
    source VARCHAR(20) NOT NULL,
    -- Set by the CSV import (the file's lot_ref) and by show mode (an id made on the phone), so importing the
    -- same file twice or retrying a sync never adds the lot twice
    external_ref VARCHAR(80) UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ledger_lots_kind ON ledger_lots (kind);

CREATE TABLE IF NOT EXISTS ledger_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id BIGINT NOT NULL REFERENCES ledger_lots (id),
    sold_on DATE NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_cad NUMERIC(12, 2) NOT NULL CHECK (unit_price_cad >= 0),
    channel VARCHAR(30) NOT NULL,
    payment_method VARCHAR(20),
    notes VARCHAR(500),
    source VARCHAR(20) NOT NULL,
    -- Set by show mode for each queued entry so a retried sync never records a sale twice
    client_ref VARCHAR(80) UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ledger_sales_lot ON ledger_sales (lot_id);
CREATE INDEX IF NOT EXISTS idx_ledger_sales_sold_on ON ledger_sales (sold_on);
