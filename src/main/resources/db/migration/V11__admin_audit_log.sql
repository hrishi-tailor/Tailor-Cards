-- Append-only log of admin actions: who, what, when, and the record before and after (JSON).
-- The application only ever inserts; on PostgreSQL a trigger also rejects UPDATE, DELETE and
-- TRUNCATE (db.migration.V11_1__admin_audit_log_append_only), so entries can't be changed or removed even with
-- direct database access through the app's role.
CREATE TABLE IF NOT EXISTS admin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor VARCHAR(100) NOT NULL,
    actor_role VARCHAR(20),
    action VARCHAR(60) NOT NULL,
    entity_type VARCHAR(40),
    entity_id VARCHAR(100),
    before_json TEXT,
    after_json TEXT,
    ip VARCHAR(64),
    request_path VARCHAR(200)
);
CREATE INDEX IF NOT EXISTS idx_admin_audit_log_entity ON admin_audit_log (entity_type, entity_id, id);
CREATE INDEX IF NOT EXISTS idx_admin_audit_log_action ON admin_audit_log (action, id);
